import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import {mediaFixture} from './reflections.mjs';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const origin=process.env.L2E_TEST_ORIGIN,block=Number(process.env.L2E_TEST_BLOCK);
assert.ok(origin?.startsWith('http://127.0.0.1:'));
const output=resolve('../test-results/ui');await mkdir(output,{recursive:true});
const browser=await chromium.launch();
const evidence={realGin:true,isolatedPostgres:true,realFileStorageInTemporaryDirectory:true,checks:[]};
try {
    const context=await browser.newContext({viewport:{width:390,height:844},timezoneId:'Africa/Lagos'});
    await context.addCookies([{name:'l2e_session',value:process.env.L2E_TEST_OWNER_TOKEN,url:origin,httpOnly:true,sameSite:'Lax'},{name:'l2e_scope',value:'a'.repeat(32),url:origin,sameSite:'Lax'}]);
    await context.addInitScript(mediaFixture);
    const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.clock.setFixedTime(new Date('2026-11-23T10:00:00+01:00'));
    await page.goto(origin+'/timetable');await page.locator('.timetable-day-nav [data-day="2"]').click();
    await page.locator(`[data-reflect="${block}"]`).click();
    await page.locator('#saveReflectionButton').click();await page.locator('#reflectionFormError').getByText(/Add what you did/).waitFor();
    await page.locator('#reflectionSummary').fill('Private real-server browser reflection.');
    await page.locator('#modeSpeakTab').click();await page.locator('#voiceRecordBtn').click();await page.getByRole('button',{name:'Stop recording',exact:true}).waitFor();
    await page.getByRole('button',{name:'Stop recording',exact:true}).click();await page.locator('#voiceAttachedLabel').waitFor();
    const path=await page.locator('#url-summary').inputValue();assert.match(path,/^\/uploads\//);
    await page.locator('#saveReflectionButton').click();await page.locator('#reflectionModal').waitFor({state:'hidden'});
    await page.locator('#day-2').getByText('Reflection added',{exact:false}).waitFor();
    assert.equal(await page.locator('.timetable-day-nav [data-day="2"]').getAttribute('aria-pressed'),'true');
    evidence.checks.push('Text validation, signed-in upload and voice/text save through real Gin/PostgreSQL');
    const media=await context.request.get(origin+path,{headers:{Range:'bytes=0-3'}});assert.equal(media.status(),206);assert.equal((await media.body()).toString(),'RIFF');
    assert.equal(media.headers()['cache-control'],'private, no-store');
    const other=await browser.newContext();await other.addCookies([{name:'l2e_session',value:process.env.L2E_TEST_OTHER_TOKEN,url:origin,httpOnly:true,sameSite:'Lax'},{name:'l2e_scope',value:'b'.repeat(32),url:origin,sameSite:'Lax'}]);
    assert.equal((await other.request.get(origin+path)).status(),404);
    const otherHistory=await other.request.get(origin+'/api/v1/reflections');assert.deepEqual(await otherHistory.json(),[]);
    const badSave=await other.request.post(origin+'/api/v1/reflections',{headers:{Origin:origin},data:{timetable_id:block,log_date:'2026-11-23',summary:'Foreign write attempt',audio_url:path}});assert.equal(badSave.status(),404);
    const guest=await browser.newContext();assert.equal((await guest.request.get(origin+path)).status(),401);
    assert.equal((await guest.request.get(origin+'/api/v1/reflections')).status(),401);
    evidence.checks.push('Guest and other-account read/write/media access denied; owner audio range requests work');
    await page.locator('#day-2 .bg-gray-50').getByRole('button',{name:'Delete',exact:true}).click();
    await page.waitForFunction(()=>!document.getElementById('confirmDeleteBlock').disabled);
    assert.match(await page.locator('#deleteBlockDescription').textContent(),/Saved reflections/);
    await page.locator('#confirmDeleteBlock').click();await page.getByText('Time block removed. Saved reflections remain in your history.',{exact:true}).waitFor();
    await page.goto(origin+'/reflections');await page.locator('.history-card').getByText('Private real-server browser reflection.',{exact:false}).waitFor();
    await page.getByText('Time block removed · reflection kept in your history',{exact:true}).waitFor();
    await page.locator('#reflectionSearch').fill('Learn Go');assert.equal(await page.locator('.history-card').count(),1);
    await page.selectOption('#reflectionMediaFilter','voice');assert.equal(await page.locator('.history-card').count(),1);
    await page.locator('.history-card audio').evaluate(audio=>audio.play());
    assert.equal((await context.request.get(origin+path)).status(),200);
    await page.screenshot({path:output+'/real-server-history-390.png'});
    evidence.checks.push('Verified database retention before deletion; detached reflection and private audio survive deletion and native playback');
    assert.deepEqual(errors,[]);await other.close();await guest.close();await context.close();
    console.log('Real Gin/PostgreSQL reflection browser journey passed.');
}finally {await writeFile(output+'/real-server-evidence.json',JSON.stringify(evidence,null,2));await browser.close();}
